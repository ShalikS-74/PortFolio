/* ── Precompute bounding boxes for early-exit polygon testing ──────── */
// Some polygons (like Fiji) cross the antimeridian (180°/-180°).
// We shift their longitudes so the polygon is entirely in [180, 540] range.
const POLY_BBOXES = CONTINENTS.map((c) => {
  const lons = c.points.map((p) => p[0]);
  const lats = c.points.map((p) => p[1]);
  const minLon = Math.min(...lons);
  const maxLon = Math.max(...lons);

  // Detect antimeridian crossing: if span > 180°, the polygon crosses the line
  if (maxLon - minLon > 180) {
    // Shift all longitudes by +360 for negative values to normalize
    const shiftedLons = lons.map((l) => (l < 0 ? l + 360 : l));
    return {
      minLon: Math.min(...shiftedLons),
      maxLon: Math.max(...shiftedLons),
      minLat: Math.min(...lats),
      maxLat: Math.max(...lats),
      antimeridian: true as const,
    };
  }

  return { minLon, maxLon, minLat: Math.min(...lats), maxLat: Math.max(...lats) };
});

/* ── Geometry helpers ──────────────────────────────────────────────── */
function pointInPolygon(lon: number, lat: number, points: LonLat[]) {
  let inside = false;

  for (let i = 0, j = points.length - 1; i < points.length; j = i, i += 1) {
    const current = points[i];
    const previous = points[j];

    if (!current || !previous) continue;

    const [xi, yi] = current;
    const [xj, yj] = previous;

    if (
      yi > lat !== yj > lat &&
      lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi
    ) {
      inside = !inside;
    }
  }

  return inside;
}

// Test point-in-polygon with antimeridian handling
function testLand(lon: number, lat: number, polyIndex: number): boolean {
  const bbox = POLY_BBOXES[polyIndex];
  const points = CONTINENTS[polyIndex].points;

  // Quick bbox check
  if (lat < bbox.minLat || lat > bbox.maxLat) return false;

  // For antimeridian-crossing polygons, shift the test point's longitude
  if (bbox.antimeridian) {
    const shiftedLon = lon < 0 ? lon + 360 : lon;
    if (shiftedLon >= bbox.minLon && shiftedLon <= bbox.maxLon) {
      // Create shifted polygon (negative longitudes → +360)
      const shiftedPoints: LonLat[] = points.map(([pLon, pLat]) => [
        pLon < 0 ? pLon + 360 : pLon,
        pLat,
      ]);
      return pointInPolygon(shiftedLon, lat, shiftedPoints);
    }
    return false;
  }

  // Standard test
  if (lon >= bbox.minLon && lon <= bbox.maxLon) {
    return pointInPolygon(lon, lat, points);
  }

  return false;
}

function getLandColor(lon: number, lat: number) {
  // 0.5-degree cache resolution for finer coastlines
  const key = `${Math.round(lon * 2) / 2}:${Math.round(lat * 2) / 2}`;
  const cached = LAND_CACHE.get(key);

  if (cached !== undefined) return cached;

  for (let i = 0; i < CONTINENTS.length; i++) {
    if (testLand(lon, lat, i)) {
      LAND_CACHE.set(key, CONTINENTS[i].color);
      return CONTINENTS[i].color;
    }
  }

  LAND_CACHE.set(key, null);
  return null;
}

/* ── Color utilities ───────────────────────────────────────────────── */
function hexRgb(hex: string): [number, number, number] {
  return [
    parseInt(hex.slice(1, 3), 16),
    parseInt(hex.slice(3, 5), 16),
    parseInt(hex.slice(5, 7), 16),
  ];
}

/* ── ASCII globe renderer ──────────────────────────────────────────── */
function drawAsciiGlobe(
  ctx: CanvasRenderingContext2D,
  width: number,
  height: number,
  rotationDegrees: number,
  cells: GlobeCell[],
  rows: number,
) {
  ctx.clearRect(0, 0, width, height);
  // Fill with darkest ocean color so any micro-gaps blend in
  ctx.fillStyle = '#080820';
  ctx.fillRect(0, 0, width, height);

  const cellWidth = width / rows;
  const cellHeight = height / rows;
  ctx.font = `bold ${(cellHeight * 0.95).toFixed(1)}px "JetBrains Mono", "Courier New", monospace`;
  ctx.textAlign = 'center';
  ctx.textBaseline = 'middle';

  for (const cell of cells) {
    const lonRaw = cell.lonBase + rotationDegrees;
    const lon = ((lonRaw % 360) + 360) % 360 - 180;
    const land = getLandColor(lon, cell.lat);

    let r: number;
    let g: number;
    let b: number;
    let char: string;

    if (land) {
      char = LAND_CHARS[Math.min(2, Math.floor(cell.brightness * 3))];
      const [lr, lg, lb] = hexRgb(land);
      const factor = 0.3 + 0.7 * cell.brightness;
      r = Math.round(lr * factor);
      g = Math.round(lg * factor);
      b = Math.round(lb * factor);
    } else {
      char = OCEAN_CHARS[Math.min(2, Math.floor(cell.brightness * 3))];
      r = Math.round(8 * cell.brightness);
      g = Math.round(120 * cell.brightness);
      b = Math.round(210 + 45 * cell.brightness);
    }

    const colorStr = `rgb(${r}, ${g}, ${b})`;
    // Draw a filled rectangle behind each character to eliminate gaps between cells
    ctx.fillStyle = colorStr;
    ctx.fillRect(cell.px - cellWidth / 2, cell.py - cellHeight / 2, cellWidth, cellHeight);
    ctx.fillStyle = colorStr;
    ctx.fillText(char, cell.px, cell.py);
  }
}

/* ── Globe cell builder ────────────────────────────────────────────── */
function buildGlobeCells(
  width: number,
  height: number,
  cols: number,
  rows: number,
): GlobeCell[] {
  const cells: GlobeCell[] = [];
  const cellWidth = width / cols;
  const cellHeight = height / rows;
  const radius = Math.min(width, height) / 2;
  const centerX = width / 2;
  const centerY = height / 2;
  const lx = -0.28;
  const ly = -0.28;
  const lz = 1;
  const lightLength = Math.sqrt(lx * lx + ly * ly + lz * lz);
  const nlx = lx / lightLength;
  const nly = ly / lightLength;
  const nlz = lz / lightLength;

  for (let row = 0; row < rows; row += 1) {
    for (let col = 0; col < cols; col += 1) {
      const px = (col + 0.5) * cellWidth;
      const py = (row + 0.5) * cellHeight;
      const sx = (px - centerX) / radius;
      const sy = (py - centerY) / radius;
      const sz2 = 1 - sx * sx - sy * sy;

      if (sz2 < 0) continue;

      const sz = Math.sqrt(sz2);
      const lat = Math.asin(-sy) * (180 / Math.PI);
      const lonBase = Math.atan2(sx, sz) * (180 / Math.PI);
      const diffuse = Math.max(0, sx * nlx + sy * nly + sz * nlz);
      const brightness = 0.12 + 0.88 * diffuse;

      cells.push({ px, py, lat, lonBase, brightness });
    }
  }

  return cells;
}

/* ── Component ─────────────────────────────────────────────────────── */
export default function CompassGlobe() {
  const canvasRef = useRef<HTMLCanvasElement>(null);
  const containerRef = useRef<HTMLDivElement>(null);

  const shouldAnimate = true;
  const cellsPerSide = DESKTOP_GLOBE_CELLS;
  const frameBudget = FRAME_BUDGET;
  const rotationSpeed = DEG_PER_SEC;

  useEffect(() => {
    const canvas = canvasRef.current;
    const container = containerRef.current;
    if (!canvas || !container) return undefined;

    const ctx = canvas.getContext('2d');
    if (!ctx) return undefined;

    let raf = 0;
    let lastFrame = 0;
    let cells: GlobeCell[] = [];

    // Fixed high-res canvas buffer — CSS scales it to fit the container
    const BUFFER = 1000;
    canvas.width = BUFFER;
    canvas.height = BUFFER;
    cells = buildGlobeCells(BUFFER, BUFFER, cellsPerSide, cellsPerSide);

    if (!shouldAnimate) {
      drawAsciiGlobe(ctx, BUFFER, BUFFER, 0, cells, cellsPerSide);
      return undefined;
    }

    const start = performance.now();
    const tick = (now: number) => {
      raf = requestAnimationFrame(tick);

      if (now - lastFrame < frameBudget) return;

      lastFrame = now;
      drawAsciiGlobe(
        ctx,
        BUFFER,
        BUFFER,
        ((now - start) / 1000) * rotationSpeed,
        cells,
        cellsPerSide,
      );
    };

    raf = requestAnimationFrame(tick);

    return () => cancelAnimationFrame(raf);
  }, [cellsPerSide, frameBudget, rotationSpeed, shouldAnimate]);

  return (
    <div
      className="pointer-events-none absolute left-1/2 top-[54%] z-0 hidden h-[clamp(500px,40vw,720px)] w-[clamp(500px,40vw,720px)] -translate-x-1/2 -translate-y-1/2 select-none opacity-42 md:block md:left-auto md:right-[4vw] md:top-1/2 md:h-[clamp(500px,40vw,720px)] md:w-[clamp(500px,40vw,720px)] md:translate-x-0 md:opacity-100 xl:right-[5vw]"
      aria-hidden="true"
    >
      <style>{`
        @keyframes moonOrbit {
          from { transform: rotate(0deg); }
          to { transform: rotate(360deg); }
        }
      `}</style>

      <div
        className="absolute inset-[-11%]"
        style={{
          transform: 'rotateZ(-18deg) scaleY(0.42)',
        }}
      >
        <div
          className="absolute inset-0 rounded-full border border-black/20"
          style={{
            boxShadow:
              '0 0 22px rgba(47, 92, 255, 0.14), inset 0 0 18px rgba(47, 92, 255, 0.08)',
          }}
        />
        <div
          className="absolute inset-0"
          style={{
            animation: shouldAnimate ? 'moonOrbit 11s linear infinite' : 'none',
          }}
        >
          <span
            className="absolute left-1/2 top-[-6px] block rounded-full bg-[color:var(--ivory)]"
            style={{
              width: 'clamp(9px, 1.1vw, 15px)',
              height: 'clamp(9px, 1.1vw, 15px)',
              transform: 'translateX(-50%) scaleY(2.38)',
              boxShadow:
                '0 0 0 1px rgba(11, 11, 12, 0.2), 0 0 18px rgba(180, 220, 255, 0.65)',
            }}
          />
        </div>
      </div>

      <div
        ref={containerRef}
        className="absolute inset-0 overflow-hidden rounded-full"
        style={{
          boxShadow:
            '0 0 0 1px rgba(11,11,12,0.22), 0 22px 70px rgba(0, 32, 120, 0.18), 0 0 46px rgba(47,92,255,0.18)',
        }}
      >
        <canvas
          ref={canvasRef}
          style={{ width: '100%', height: '100%', display: 'block' }}
        />
      </div>
    </div>
  );
}
